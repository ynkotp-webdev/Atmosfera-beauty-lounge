type Svc = { name: string; duration: string | null; price: number };
const [L, N] = bloknot.locations;
const flat = (loc: typeof L): Svc[] => loc.categories.flatMap((c) => c.services as Svc[]);
const index = (list: Svc[]) => new Map(list.map((s) => [s.name, s]));
const lounge = index(flat(L).filter((s) => !s.name.startsWith('.')));
const nailbar = index(flat(N));

