export type Row = { label: string; incl?: string; addon?: boolean; minor?: boolean; time: string; timeN?: string; l?: number; n?: number };
type Def = { label: string; incl?: string; addon?: boolean; minor?: boolean; l?: string; n?: string };
export type Group = { id?: string; title?: string; rows: Row[]; foot?: string };
export type Section = { id: string; title: string; note?: string; groups: Group[] };

const used = { l: new Set<string>(), n: new Set<string>() };
const row = (d: Def): Row => {
  const a = d.l ? lounge.get(d.l) : undefined;
  const b = d.n ? nailbar.get(d.n) : undefined;
  if (d.l && !a) throw new Error(`prices: у Lounge немає «${d.l}»`);
  if (d.n && !b) throw new Error(`prices: у Nail Bar немає «${d.n}»`);
  if (d.l) used.l.add(d.l);
  if (d.n) used.n.add(d.n);
  const dur = (s?: Svc) => (s?.duration && s.duration !== '—' ? s.duration : '');
  const time = dur(a) || dur(b);
  return { label: d.label, incl: d.incl, addon: d.addon, minor: d.minor, time, timeN: a && b && dur(b) && dur(b) !== dur(a) ? dur(b) : undefined, l: a?.price, n: b?.price };
};
// both: та сама назва в обох списках. ln: різні назви. lo: тільки Шевченка. no: тільки Залізнична
const both = (label: string, name: string, o: Partial<Def> = {}) => row({ label, l: name, n: name, ...o });
const ln = (label: string, l: string, n: string, o: Partial<Def> = {}) => row({ label, l, n, ...o });
const lo = (label: string, l: string, o: Partial<Def> = {}) => row({ label, l, ...o });
